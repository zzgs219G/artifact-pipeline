/*
 * nc_log.h — 文件日志通道的唯一契约（2026-11-25）
 *
 * ═══ 一句话逻辑 ═══
 * 要写日志时，如果日志目录还没建好，就等 2 秒再查；建好了就直接写。
 *
 * ═══ 为什么有这个模块 ═══
 * 抽取前，sig_check.c 与 env_check.c 各自实现了几乎逐行相同的一份日志
 * （siglog_* 与 envlog_*），都写同一个文件 sigcheck_log.txt，各自探测
 * 哨兵、各自维护 ready 状态。实测代价：修"首次启动没日志"时只改了
 * sig_check.c，env_check.c 仍是老写法 → 中文文案照样丢 = 同一个 bug
 * 存在两份，只修一半。
 *
 * 合并后只有一个状态机，不存在"一边开了另一边没开"的错位。
 *
 * ⚠️ 不违反 AGENTS §1「零代码共享」：那条纪律针对【判定逻辑】
 *    （sig_guard2 必须独立实现，否则改一处两线同废）。日志是可观测性
 *    设施，共享不削弱任何防线 —— 攻击者改掉日志模块最多让日志消失，
 *    判定与处置照常。判定链（sig_collect_fp / derive_expected / g2_verify）
 *    仍然零共享。
 *
 * ═══ 关于"目录没建"的实测结论（决定了实现）═══
 *   · 日志目录 /…/<pkg>/files 不是系统在启动时建，而是【第一次有文件
 *     写入时才被隐式创建】。而本 so 的 constructor 跑在那之前 → 第一次
 *     写日志时目录必然不存在。
 *   · <pkg>/ 这层 App 无权自建：父目录 Android/data 权限是 drwxrws--x
 *     （其他用户 --x，能进不能写），mkdir 必然 EACCES(13)。真机实测确认。
 *   · 目录出现的时间不可预测（实测 2 秒 ~ 104 秒）。
 *
 * 所以只能"等 + 再查"，且等待必须有界（见下）。
 */
#ifndef NC_LOG_H
#define NC_LOG_H

#include <stddef.h>

/* 等待参数：目录没建时等待多久、最多等几轮。
 *
 * 2 秒 × 5 轮 = 最多 10 秒。取值依据：
 *   · 2 秒：实测最快案例是 2.13 秒就绪（09:19 那次），2 秒粒度够；
 *     更密（如 200ms）会让启动多几十次 access()，收益不抵成本。
 *   · 5 轮：覆盖"启动后 10 秒内就绪"的绝大多数情况。
 *     实测最坏 104 秒的那次是个例外（会放弃，日志只留 logcat）。
 *
 * ⚠️ 只有【首条日志】会走这个等待循环；一旦就绪，后续日志零等待。
 *    所以最坏影响是"进程启动慢 10 秒"，不会让每条日志都慢。 */
#define NC_LOG_WAIT_MS     2000
#define NC_LOG_WAIT_TRIES  5

/* 探测开关并准备路径。返回 1 = 可写，0 = 不可写。
 *
 * ⚠️ 内部会阻塞最多 NC_LOG_WAIT_MS × NC_LOG_WAIT_TRIES 毫秒。
 *    首次调用发生在 constructor 里，那时目录通常还没建好，所以会等。
 *    这是刻意的：见头注「为什么只能等」。
 * ⚠️ 幂等：已就绪或已放弃时立即返回，不阻塞。 */
int  nc_log_open(void);

/* 写一行日志。fmt 之后是 printf 风格参数，内部按 512 字节截断。
 * prio 取 "I" / "E" / "D" / "W"（单字符，与既有日志格式一致）。
 * 未就绪时会尝试 nc_log_open()（含等待）；仍不可写则打到 logcat
 * 并加 `[no-file]` 标记，保证排障不丢信息。 */
void nc_log_line(const char *prio, const char *fmt, ...);

/* 当前是否可写（1=可以，0=否）。 */
int  nc_log_ready(void);

#endif /* NC_LOG_H */
